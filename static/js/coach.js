/* GymPulse AI - coach page */
(function () {
  "use strict";
  if (document.body.dataset.page !== "coach") return;

  const btn = document.getElementById("run-analysis");
  const box = document.getElementById("insights");

  const ICON = { good: "circle-check", warn: "triangle-alert", info: "info",
                 attendance: "calendar-check", streak: "flame", muscles: "dumbbell",
                 strength: "trophy", volume: "bar-chart-3" };

  async function run() {
    btn.disabled = true;
    box.innerHTML = "<div class='card'><p class='muted small'>Analysing your real records…</p></div>";
    try {
      const data = await GP.api("/api/ai/analyze", { method: "POST", body: "{}" });
      const nar = document.getElementById("ai-narrative");
      if (data.ai.used_ai && data.ai.text) {
        nar.hidden = false;
        document.getElementById("ai-text").textContent = data.ai.text;
        document.getElementById("ai-source").textContent = "Generated by " + data.source + " at " + data.generated_at;
      } else {
        nar.hidden = false;
        document.getElementById("ai-text").textContent =
          "No AI narrative was generated. " + (data.ai.reason || "");
        document.getElementById("ai-source").textContent = "Source: " + data.source;
      }

      box.innerHTML = data.insights.map((i) =>
        "<div class='card reveal'><div class='row-between'><h3><i data-lucide='" +
        (ICON[i.type] || "info") + "'></i> " + GP.escape(i.title) + "</h3></div>" +
        "<p class='muted small'>" + GP.escape(i.body) + "</p></div>").join("");

      const s = data.summary;
      box.innerHTML += "<div class='card reveal'><h3>Key numbers</h3><ul class='kv'>" + [
        ["Total sessions", s.total_sessions], ["Gym days", s.total_gym_visits],
        ["Missed days", s.total_missed_days], ["Rest days", s.total_rest_days],
        ["Unrecorded days", s.unrecorded_days], ["Attendance", s.attendance_pct + "%"],
        ["Total hours", s.total_hours], ["Avg duration", Math.round(s.avg_duration) + " min"],
        ["Avg sessions/week", s.avg_sessions_per_week], ["Training volume", s.total_volume + " kg·reps"],
        ["Data completeness", data.quality.completeness_pct + "%"]
      ].map((r) => "<li><span>" + r[0] + "</span><b>" + r[1] + "</b></li>").join("") + "</ul></div>";

      GP.reveal(box); GP.icons();
    } catch (e) {
      box.innerHTML = "<div class='card'><p class='form-error'>" + GP.escape(e.message) + "</p></div>";
    } finally {
      btn.disabled = false;
    }
  }

  btn.addEventListener("click", run);
  run();
})();
